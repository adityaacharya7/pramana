def call_gemini(
    prompt: str,
    system_instruction: str | None = None,
    response_json: bool = False,
    temperature: float = 0.2,
    timeout_sec: float = 25.0,
) -> str:
    """Call Google Gemini API with automatic model fallback."""
    api_key = get_gemini_api_key()
    last_error: Exception | None = None

    payload: dict[str, Any] = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "temperature": temperature,
        },
    }
    if system_instruction:
        payload["systemInstruction"] = {
            "parts": [{"text": system_instruction}]
        }
    if response_json:
        payload["generationConfig"]["responseMimeType"] = "application/json"

    for model in GEMINI_MODELS:
        url = f"{BASE_URL}/models/{model}:generateContent?key={api_key}"
        try:
            with httpx.Client(timeout=timeout_sec) as client:
                res = client.post(url, json=payload)
                if res.status_code == 200:
                    data = res.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if parts:
                            return parts[0].get("text", "")
                    return "No output generated by AI model."
                elif res.status_code in (404, 503, 429):
                    logger.warning("Gemini model %s returned status %d, trying fallback...", model, res.status_code)
                    last_error = RuntimeError(f"Model {model} returned status {res.status_code}")
                    continue
                else:
                    res.raise_for_status()
        except Exception as exc:
            logger.warning("Gemini model %s failed: %s", model, exc)
            last_error = exc
            continue

    if last_error:
        raise RuntimeError(f"All Gemini models failed. Last error: {last_error}")
    raise RuntimeError("No Gemini model responded.")


