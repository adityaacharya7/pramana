def chat_case_intelligence(
    message: str,
    case_context: dict[str, Any] | None = None,
    history: list[dict[str, str]] | None = None,
    db_extra_context: str | None = None,
) -> str:
    """Answer investigator queries with grounded, interconnected case and syndicate context."""
    active_str = ""
    if case_context:
        active_str = f"""
CURRENT ACTIVE SCREEN CONTEXT:
Case ID: {case_context.get('id', 'N/A')}
FIR No: {case_context.get('fir_no', 'N/A')} | Title: {case_context.get('title', 'N/A')}
Complainant: {case_context.get('complainant', 'N/A')} | City: {case_context.get('city', 'N/A')}
Station: {case_context.get('station', 'N/A')} | Unit: {case_context.get('unit', 'N/A')}
Status: {case_context.get('status', 'OPEN')} | Reg Date: {case_context.get('registered_on', 'N/A')}
Evidence Files: {case_context.get('evidence_count', 0)}
"""

    extra_str = db_extra_context or ""

    history_str = ""
    if history:
        for turn in history[-6:]:
            role = "Investigating Officer" if turn.get("role") in ("user", "human") else "PRAMANA AI"
            history_str += f"{role}: {turn.get('content', '')}\n"

    prompt = f"""
{active_str}
{extra_str}

CONVERSATION HISTORY:
{history_str}

INVESTIGATOR QUERY:
{message}

Provide a direct, fact-checked, deeply integrated forensic intelligence response.
"""
    system_instruction = get_omniscient_system_prompt()
    raw_res = call_gemini(prompt, system_instruction=system_instruction, temperature=0.25)
    
    # Clean up any leftover memo headers if Gemini generated them
    clean_res = re.sub(r"^\*\*PRAMANA AI // [^\n]+\*\*\s*", "", raw_res, flags=re.IGNORECASE)
    clean_res = re.sub(r"^\*\*TO:\*\*[^\n]+\n", "", clean_res, flags=re.IGNORECASE)
    clean_res = re.sub(r"^\*\*SUBJECT:\*\*[^\n]+\n", "", clean_res, flags=re.IGNORECASE)
    clean_res = re.sub(r"^\*\*DATE:\*\*[^\n]+\n", "", clean_res, flags=re.IGNORECASE)
    return clean_res.strip()


